export function createCsvFallbackOptions() {
  const pestGroups = CSV_PEST_GROUPS.map((group) => ({
    category: group.category,
    items: [...group.items],
  }));
  const pests = pestGroups
    .flatMap((group) => group.items)
    .sort((left, right) => left.localeCompare(right, "ko"));
  const pestCategories = Object.fromEntries(
    pestGroups.flatMap((group) => group.items.map((item) => [item, group.category])),
  );

  return {
    crops: [...CSV_FALLBACK_CROPS],
    regions: [...CSV_FALLBACK_REGIONS],
    pests,
    pest_categories: pestCategories,
    pest_groups: pestGroups,
  };
}
